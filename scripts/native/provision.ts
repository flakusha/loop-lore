/**
 * Provision the official wasm32 std component for one host install.
 *
 * Split out of toolchain.ts: discovery (what is this host) and provisioning
 * (fetch + install + wrap) fail independently and are read independently -
 * operators diagnosing "which rustc did it pick" never need the download
 * logic, and vice versa.
 *
 * Contract: the overlay is idempotent. A populated wasm32 std dir means the
 * second call skips the download entirely and just re-writes the wrapper.
 */
import { spawnSync, } from "node:child_process";
import { createHash, } from "node:crypto";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { join, } from "node:path";
import { DIST_BASE, OVERLAY_ROOT, type RustcInstall, WASM_TARGET, } from "./shared";

/**
 * Download the version-matched official component and verify its sha256
 * against the sidecar served next to it.
 *
 * @param url component tarball URL
 * @param destination local tarball path
 */
function downloadComponent(url: string, destination: string,): void {
  const result = spawnSync("curl", ["-fL", "-o", destination, url,], { stdio: "inherit", },);
  if (result.status !== 0) {
    throw new Error(`download failed (curl status ${result.status}): ${url}`,);
  }

  const sidecar = spawnSync("curl", ["-fsSL", `${url}.sha256`,], { encoding: "utf8", },);
  if (sidecar.status !== 0) {
    throw new Error(`failed to fetch ${url}.sha256 (curl status ${sidecar.status})`,);
  }

  const expected = sidecar.stdout.trim().split(/\s+/,)[0];
  const actual = createHash("sha256",).update(readFileSync(destination,),).digest("hex",);
  if (expected !== actual) {
    throw new Error(`sha256 mismatch for ${destination}: expected ${expected}, got ${actual}`,);
  }
}

/**
 * Install the official wasm32 std component into a repo-local overlay and
 * return the RUSTC wrapper that points rustc at it via `--sysroot`.
 *
 * The overlay REFERENCES the host install (symlinks to its host rustlib and
 * bin/) - nothing is copied between installs, no sudo is needed, and the
 * wrapper mechanism is the same one rustup uses for its proxies.
 *
 * @param install version-matched host install (known to lack the wasm std)
 * @param log optional progress sink
 * @returns absolute path to the RUSTC wrapper
 */
export function provisionWasmStd(install: RustcInstall, log?: (line: string,) => void,): string {
  const prefix = join(OVERLAY_ROOT, `${install.version}-${install.host}`,);
  const sysroot = join(prefix, "sysroot",);
  const wrapper = join(prefix, "rustc",);
  const wasmDir = join(sysroot, "lib", "rustlib", WASM_TARGET,);
  mkdirSync(sysroot, { recursive: true, },);

  // wasmDir does not exist yet on a fresh prefix - readdir would throw ENOENT.
  if (!existsSync(wasmDir,) || readdirSync(wasmDir, { recursive: true, },).length === 0) {
    const component = `rust-std-${install.version}-${WASM_TARGET}`;
    const url = `${DIST_BASE}/${component}.tar.xz`;
    const tarball = join(prefix, `${component}.tar.xz`,);
    log?.(`[toolchain] fetching ${component} from ${url}`,);
    downloadComponent(url, tarball,);
    const extracted = spawnSync("tar", ["-xJf", tarball,], { cwd: prefix, stdio: "inherit", },);
    if (extracted.status !== 0) {
      throw new Error(`tar extract failed (status ${extracted.status}) for ${tarball}`,);
    }

    const installer = join(prefix, component, "install.sh",);
    if (!existsSync(installer,)) {
      throw new Error(`extract produced no installer: ${installer} missing`,);
    }

    chmodSync(installer, 0o755,);
    // rust-installer parses value options in --opt=VALUE form only.
    const installed = spawnSync(
      "sh",
      [installer, `--prefix=${sysroot}`, "--disable-ldconfig",],
      { stdio: "inherit", },
    );

    if (installed.status !== 0) {
      // A half-installed overlay is worse than no overlay: the next call sees a
      // populated wasm dir, skips the download and hands out a broken wrapper.
      rmSync(sysroot, { recursive: true, force: true, },);
      throw new Error(`rust-std install.sh failed (status ${installed.status})`,);
    }
  }

  // Reference, never copy, the host install: host std for build scripts and
  // proc macros, bin/ for the real rust-lld the wrapper's rustc resolves.
  for (
    const [source, target,] of [
      [join(install.sysroot, "lib", "rustlib", install.host,), join(sysroot, "lib", "rustlib", install.host,),],
      [join(install.sysroot, "bin",), join(sysroot, "bin",),],
    ] as const
  ) {
    if (!existsSync(target,)) { symlinkSync(source, target, "dir",); }
  }

  writeFileSync(
    wrapper,
    [
      "#!/bin/sh",
      `# Generated by scripts/native/toolchain.ts - wasm std overlay for ${install.path}`,
      `exec "${install.path}" --sysroot="${sysroot}" "$@"`,
      "",
    ].join("\n",),
    { mode: 0o755, },
  );

  return wrapper;
}
