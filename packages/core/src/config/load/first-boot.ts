// src/config/load/first-boot.ts — First-boot PII secret promotion
//
// Fresh clone plus plain `bun run start` with no env vars fails at
// validatePiiSafety: unset NODE_ENV counts as production-like, so the three
// PII secrets throw before any dev fallback can apply. This module closes
// that gate on the promoted-random-secret path: when no config file exists
// anywhere and at least one PII secret is unresolvable, generate >= 32-char
// secrets, persist them to gitignored `config.local.yaml` (chmod 0600), and
// merge them into the in-memory config so the same boot validates.
//
// Write-once: any pre-existing config file skips promotion entirely (the
// operator owns that config; validatePiiSafety then throws its documented
// error). Concurrent first boots serialize on O_EXCL — the loser keeps its
// own generated in-memory values and boots; the winner's file wins on disk.
// A failed promotion never blocks boot with a half-state: without a file to
// write to, behavior is exactly today's throw.

import { getLogger, } from "@/logger";
import { findMainRepoRoot, } from "@/utils/git-worktree";
import fs from "node:fs";
import path from "node:path";
import type { Config, } from "../schema";
import {
  DEFAULT_CONFIG_FILES,
  DOMAIN_CONFIG_EXTENSIONS,
  DOMAINS,
  LOCAL_CONFIG_FILES,
} from "./constants";
import { findConfigFile, } from "./fs";
import { deepMerge, } from "./parse";
import {
  isDevEnv,
  resolveNsfwPiiSecret,
  resolveReporterHashSecret,
  resolveTelemetryPiiSecret,
} from "./pii-safety";

/** Gitignored per-developer file the generated secrets are promoted into. */
export const FIRST_BOOT_FILE = "config.local.yaml";

/** Random bytes per generated secret: 48 bytes -> 64 base64 chars. */
export const GENERATED_SECRET_BYTES = 48;

/** Secrets generated by one promotion run; only missing ones are set. */
export interface FirstBootSecrets {
  nsfwPiiSecret?: string;
  reporterHashSecret?: string;
  telemetryPiiSecret?: string;
}

/**
 * Generate one PII secret: 48 CSPRNG bytes, base64 (64 chars, all safe
 * inside a double-quoted YAML scalar).
 * @returns The generated secret.
 */
export function generatePiiSecret(): string {
  return crypto.getRandomValues(new Uint8Array(GENERATED_SECRET_BYTES,),).toBase64();
}

/**
 * True when any user-editable config file exists (main, local, default,
 * domain, or env candidates — same search roots as loadConfig).
 * @param directory - Project root to probe.
 * @returns True when at least one config file exists.
 */
export function hasAnyConfigFile(directory: string,): boolean {
  if (
    findConfigFile(directory,) ??
      findConfigFile(directory, LOCAL_CONFIG_FILES,) ??
      findConfigFile(directory, DEFAULT_CONFIG_FILES,)
  ) {
    return true;
  }

  const mainRoot = findMainRepoRoot(directory,);
  const candidates = [
    path.join(directory, "env.yaml",),
    path.join(directory, "configs", "env.yaml",),
    path.join(directory, "env.toml",),
    path.join(directory, "configs", "env.toml",),
  ];
  if (mainRoot && mainRoot !== directory) {
    candidates.push(
      path.join(mainRoot, "env.yaml",),
      path.join(mainRoot, "configs", "env.yaml",),
      path.join(mainRoot, "env.toml",),
      path.join(mainRoot, "configs", "env.toml",),
    );
  }
  for (const candidate of candidates) {
    if (fs.existsSync(candidate,)) { return true; }
  }

  for (const domain of DOMAINS) {
    const names = DOMAIN_CONFIG_EXTENSIONS.map((ext,) => `config.${domain}${ext}`);
    if (findConfigFile(directory, names,)) { return true; }
  }

  return false;
}

/**
 * Render the promotion file: header comment plus only the generated
 * sections, so env- or file-provided values are never echoed back.
 * @param secrets - Generated secrets (missing members are omitted).
 * @returns YAML document text.
 */
export function renderFirstBootYaml(secrets: FirstBootSecrets,): string {
  const lines = [
    "# Loop Lore first-boot secrets - generated automatically on first boot.",
    "# This file is gitignored and chmod 0600. Edit values freely; deleting it",
    "# restores fresh-clone behavior (secrets regenerate on next boot).",
  ];
  if (secrets.nsfwPiiSecret !== undefined || secrets.reporterHashSecret !== undefined) {
    lines.push("nsfw:",);
    if (secrets.nsfwPiiSecret !== undefined) { lines.push(`  piiSecret: "${secrets.nsfwPiiSecret}"`,); }
    if (secrets.reporterHashSecret !== undefined) {
      lines.push(`  reporterHashSecret: "${secrets.reporterHashSecret}"`,);
    }
  }
  if (secrets.telemetryPiiSecret !== undefined) {
    lines.push("observability:", "  telemetry:", `    piiSecret: "${secrets.telemetryPiiSecret}"`,);
  }
  return `${lines.join("\n",)}\n`;
}

/**
 * Persist the promotion file with O_EXCL (write-once across concurrent
 * first boots) and chmod 0600.
 * @param directory - Project root receiving the file.
 * @param secrets - Generated secrets to persist.
 * @returns "created" for the winner, "existed" when another boot won the race.
 */
export function writeFirstBootFile(directory: string, secrets: FirstBootSecrets,): "created" | "existed" {
  const target = path.join(directory, FIRST_BOOT_FILE,);
  try {
    fs.writeFileSync(target, renderFirstBootYaml(secrets,), { flag: "wx", mode: 0o600, },);
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "EEXIST") { return "existed"; }
    throw error;
  }
  fs.chmodSync(target, 0o600,);
  return "created";
}

/**
 * True when the resolver throws (secret unresolvable in this environment).
 * Short-but-present secrets are NOT missing: overwriting an operator value
 * is never promotion's job.
 * @param resolver - One of the resolve*PiiSecret functions, bound.
 * @returns True when the secret must be generated.
 */
function isMissingSecret(resolver: () => string,): boolean {
  try {
    resolver();
    return false;
  } catch {
    return true;
  }
}

/**
 * First-boot promotion, called from loadConfig after validateAuthSafety and
 * before validatePiiSafety. Dev environments, fully-configured environments,
 * and operator-owned configs pass through untouched.
 * @param directory - Project root (loadConfig's cwd).
 * @param config - Merged config (file layers plus env overrides applied).
 * @returns The config with generated secrets merged in, or unchanged.
 */
export function ensureFirstBootPiiSecrets(directory: string, config: Config,): Config {
  if (isDevEnv()) { return config; }

  const generated: FirstBootSecrets = {};
  if (isMissingSecret(() => resolveNsfwPiiSecret(config.nsfw,))) {
    generated.nsfwPiiSecret = generatePiiSecret();
  }
  if (isMissingSecret(() => resolveReporterHashSecret(config.nsfw,))) {
    generated.reporterHashSecret = generatePiiSecret();
  }
  if (isMissingSecret(() => resolveTelemetryPiiSecret(config.observability?.telemetry,))) {
    generated.telemetryPiiSecret = generatePiiSecret();
  }
  if (Object.keys(generated,).length === 0) { return config; }

  // Operator owns a config file: leave it alone; validatePiiSafety throws
  // the documented error naming the env var to set.
  if (hasAnyConfigFile(directory,)) { return config; }

  const log = getLogger().child({ module: "config", },);
  const outcome = writeFirstBootFile(directory, generated,);
  if (outcome === "created") {
    log.info(
      `first boot: generated PII secrets in ${FIRST_BOOT_FILE} (chmod 0600); GET /api/v1/setup/state reports remaining setup`,
    );
  } else {
    log.info(
      `first boot: ${FIRST_BOOT_FILE} already exists (concurrent boot won); using this boot's generated secrets in memory`,
    );
  }

  const patch: Record<string, unknown> = {};
  const nsfw: Record<string, string> = {};
  if (generated.nsfwPiiSecret !== undefined) { nsfw["piiSecret"] = generated.nsfwPiiSecret; }
  if (generated.reporterHashSecret !== undefined) { nsfw["reporterHashSecret"] = generated.reporterHashSecret; }
  if (Object.keys(nsfw,).length > 0) { patch["nsfw"] = nsfw; }
  if (generated.telemetryPiiSecret !== undefined) {
    patch["observability"] = { telemetry: { piiSecret: generated.telemetryPiiSecret, }, };
  }
  return deepMerge(config, patch,);
}
