// src/config/load/first-boot.ts — First-boot PII secret promotion
//
// Fresh clone plus plain `bun run start` with no env vars fails at
// validatePiiSafety: unset NODE_ENV counts as production-like, so the three
// PII secrets throw before any dev fallback can apply. This module closes
// that gate on the promoted-random-secret path: when no config file exists
// anywhere and at least one PII secret is unresolvable, generate >= 32-char
// secrets, persist them to gitignored `config.local.yaml` (chmod 0600), and
// merge them into the in-memory config so the same boot validates.
//
// Write-once: any pre-existing config file skips promotion entirely (the
// operator owns that config; validatePiiSafety then throws its documented
// error). Concurrent first boots serialize on an exactly-one-wins claim:
// the winner atomically publishes config.local.yaml while the loser discards
// its own generated values, adopts the winner's via bounded re-read, and
// boots as a non-generating follower (FirstBootContentionError after the
// retry budget, mapped to exit 75 for supervised restart).
// A failed promotion never blocks boot with a half-state: without a file to
// write to, behavior is exactly today's throw.

