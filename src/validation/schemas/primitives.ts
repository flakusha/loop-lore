// ── Hand-authored config enums (no DB counterpart) ──────────────
// Gm* members describe chat-level GM configuration JSON, not DB enums.

/** Chat-level GM configuration — stored as JSON in `chats.gm_config` */
/** Per-participant turn priority for GM-guided story guidance. */
export const GmTurnPrioritySchema = t.UnionEnum(["high", "medium", "low",],);

/** Narrative guidance a human Game Master applies to a story chat. */
export const GmGuidanceSchema = t.Object({
  constraints: t.Array(t.String(),),
  targetCharacter: t.Optional(t.String(),),
  sceneDescription: t.Optional(t.String(),),
  turnPriority: t.Record(t.String(), GmTurnPrioritySchema,),
},);

export const GmConfigSchema = t.Object({
  assistantRole: t.Optional(t.UnionEnum(["off", "helper", "gm", "moderator",],),),
  renderingOverride: t.Optional(t.Union([
    t.Literal("text",),
    t.Literal("visual_novel",),
    t.Null(),
  ],),),
  storyMode: t.Optional(t.Boolean(),),
  gmGuidance: t.Optional(GmGuidanceSchema,),
  type: t.Optional(t.UnionEnum(["llm", "human", "hybrid",],),),
  humanGM: t.Optional(t.Object({ actorId: t.String(), notifications: t.Boolean(), },),),
  escalationThreshold: t.Optional(t.Number({ minimum: 0, maximum: 1, },),),
  llmConfig: t.Optional(
    t.Object({
      model: t.String(),
      provider: t.String(),
      systemPrompt: t.String(),
      temperature: t.Number(),
      maxTokens: t.Number(),
    },),
  ),
  actorModels: t.Optional(
    t.Record(t.String(), t.Object({ model: t.String(), provider: t.String(), },),),
  ),
  // ── VN presentation keys (mutable once a chat is online) ──
  visualNovel: t.Optional(t.Boolean(),),
  vnLayout: t.Optional(t.UnionEnum(["overlay", "below", "split",],),),
  vnTypewriter: t.Optional(t.Boolean(),),
  vnTypewriterSpeed: t.Optional(t.Number(),),
  vnTransition: t.Optional(t.UnionEnum(["fade", "cut", "dissolve", "slide", "wipe",],),),
  vnAutoAdvance: t.Optional(t.Boolean(),),
  vnImageScaling: t.Optional(t.UnionEnum(["contain", "cover", "fill", "auto",],),),
  vnAutoAdvanceDelay: t.Optional(t.Number({ minimum: 0, },),),
  vnDialogueBoxOpacity: t.Optional(t.Number({ minimum: 0, maximum: 1, },),),
  vnPortraitSize: t.Optional(t.Number({ minimum: 0, },),),
  vnSplitRatio: t.Optional(t.Number({ minimum: 0, maximum: 100, },),),
  responseLengthPreset: t.Optional(t.UnionEnum(["short", "medium", "long", "custom",],),),
  responseLengthCustom: t.Optional(t.Number({ minimum: 50, maximum: 2000, },),),
  outputStyle: t.Optional(t.Union([
    t.Object({
      preset: t.Optional(t.UnionEnum([
        "neutral", "high_fantasy", "sci_fi", "modern", "noir", "cyberpunk",
        "pulp", "literary", "horror", "western", "",
      ],),),
      customInstruction: t.Optional(t.String(),),
      intensity: t.Optional(t.Number({ minimum: 0, maximum: 1, },),),
    },),
    t.Null(),
  ],),),
},);

// ── Response schemas ──────────────────────────────────────

export const ErrorResponse = t.Object({
  error: t.String(),
  code: t.Optional(t.String(),),
  details: t.Optional(t.Any(),),
},);

export const SuccessResponse = t.Object({
  data: t.Any(),
},);

/**
 * Generic list envelope: `{ data: T[], total }` for paginated list responses.
 * @param itemSchema - TypeBox schema for items in the `data` array
 * @returns TypeBox object schema `{ data: T[], total: number }`.
 */
export function ListResponse(itemSchema: Parameters<typeof t.Array>[0],) {
  return t.Object({
    data: t.Array(itemSchema,),
    total: t.Number(),
    page: t.Number(),
    pageSize: t.Number(),
  },);
}
