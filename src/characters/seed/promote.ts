// src/characters/seed/promote.ts — Promote a generated avatar to a git-tracked default
//
// Avatar Dogfood slices 1+2: after the assistant generates real character
// art through the image pipeline, the operator copies the curated PNG bytes
// into the template's default cell and flips that template's `avatar` in
// `src/config/sections/characters/defaults.ts` from `{ type: "default" }` to
// the returned `{ type: "file", path }` literal. A clean restart then seeds
// the promoted art through the existing `file` hook (`resolveTemplateAvatar`
// + `linkTemplateAvatar`, insert-once, so already-seeded actors keep their
// avatars).
//
// Master format (slice 2): the default is a LOSSLESS WEBP master (sharp,
// full size — the same dependency the thumbnail path proves). PNG input
// stays the contract (it is what `persistGeneratedImages` produces);
// conversion happens here, at promote time. `master: "png"` preserves the
// slice-1 byte-for-byte PNG cell for callers that want it.
//
// Operator runbook (no real art exists yet — ticket (a) generates it):
//   1. Generate art; fetch the asset bytes (GET /api/assets/<id>/raw).
//   2. Call `promoteAvatarToDefault({ template: { id, name }, bytes })`.
//   3. Paste the returned `avatar` literal over the template's `avatar:` line.
//   4. Commit the master + defaults.ts; wipe DB + upload dir; reboot; verify.

import { existsSync, mkdirSync, readFileSync, writeFileSync, } from "node:fs";
import { dirname, join, } from "node:path";
import sharp from "sharp";
import { slugifyName, } from "./identity";

/** PNG signature — the promote INPUT contract: generation output is PNG. */
const PNG_MAGIC = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10,],);
/** Slug charset; anything else (e.g. `../`) is rejected, never sanitized. */
const SLUG_RE = /^[a-z0-9-]+$/;

/** Minimal template identity needed to locate the default cell. */
export interface PromoteTemplate {
  id?: string;
  name: string;
}

/** Storage master format for the promoted cell. */
export type PromoteMasterFormat = "png" | "webp";

/** */
export interface PromoteAvatarOpts {
  template: PromoteTemplate;
  /** Curated generated bytes; must be a PNG (the generation output contract). */
  bytes: Buffer;
  /** Repo root the returned path is relative to. Defaults to `process.cwd()`. */
  repoRoot?: string;
  /** Storage master: lossless webp (default) or byte-for-byte PNG (slice 1). */
  master?: PromoteMasterFormat;
}

/** */
export interface PromotedAvatar {
  /** Repo-relative posix path, seed-readable from the repo root. */
  path: string;
  /** Literal to paste over the template's `avatar:` line in defaults.ts. */
  avatar: { type: "file"; path: string };
  /** False when identical bytes were already promoted (idempotent no-op). */
  replaced: boolean;
}

/**
 * Map a character template to its `configs/assets/characters/<slug>/` dir:
 * the `tpl-` id prefix stripped, falling back to the slugified name.
 * @param template
 * @returns void
 * @throws Error when no usable slug derives from the id/name.
 */
export function slugForTemplate(template: PromoteTemplate,): string {
  const raw = template.id?.startsWith("tpl-",) ? template.id.slice(4,) : slugifyName(template.name,);

  if (raw.length === 0 || !SLUG_RE.test(raw,)) {
    throw new Error(
      `promoteAvatarToDefault: cannot derive asset slug from id=${template.id ?? "(none)"} name=${template.name}`,
    );
  }

  return raw;
}

/**
 * Encode a PNG master to lossless webp at full size (sharp, the dependency
 * the thumbnail path already proves; lossless, no resize).
 * @param png - Decoded-capable image bytes (the promote input PNG).
 * @returns Lossless webp master bytes.
 * @throws {Error} when sharp cannot decode/encode the input.
 */
async function encodeLosslessWebpMaster(png: Buffer,): Promise<Buffer> {
  return await sharp(png,).webp({ lossless: true, },).toBuffer();
}

/**
 * Write curated PNG bytes into the template's default cell as the chosen
 * storage master. Same master bytes twice is a no-op; different input
 * replaces the file. Default master: lossless webp (slice 2); `"png"`
 * preserves the slice-1 byte-for-byte cell.
 * @param opts
 * @returns void
 * @throws Error when the bytes are not a PNG, the slug is unusable, or the
 *   webp encode fails.
 */
export async function promoteAvatarToDefault(opts: PromoteAvatarOpts,): Promise<PromotedAvatar> {
  if (opts.bytes.length < PNG_MAGIC.length || !opts.bytes.subarray(0, PNG_MAGIC.length,).equals(PNG_MAGIC,)) {
    throw new Error("promoteAvatarToDefault: input masters must be PNG (generation output)",);
  }

  const slug = slugForTemplate(opts.template,);
  const master = opts.master ?? "webp";
  const rel = `configs/assets/characters/${slug}/default/happy.${master}`;
  const abs = join(opts.repoRoot ?? process.cwd(), ...rel.split("/",),);
  mkdirSync(dirname(abs,), { recursive: true, },);

  const bytes = master === "webp" ? await encodeLosslessWebpMaster(opts.bytes,) : opts.bytes;

  if (existsSync(abs,) && readFileSync(abs,).equals(bytes,)) {
    return { path: rel, avatar: { type: "file", path: rel, }, replaced: false, };
  }

  writeFileSync(abs, bytes,);
  return { path: rel, avatar: { type: "file", path: rel, }, replaced: true, };
}
