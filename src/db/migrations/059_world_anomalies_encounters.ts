/**
 * 059_world_anomalies_encounters
 *
 * Location anomalies + generic random encounters
 * (epic-world-encounters: "Implement anomaly system",
 * "Implement random encounter system").
 *
 * Three tables, none of which existed before this epic:
 *
 *   - `location_anomalies` — a world-altering overlay bound to ONE
 *     location. Effects are stored flat (stat JSON + four scalar
 *     multipliers) rather than as a nested effect blob so a consumer
 *     can sum `damage_over_time` in SQL. `duration_seconds = -1`
 *     means permanent and leaves `expires_at` NULL; anything else
 *     stamps `expires_at` at placement, which is what
 *     `expireAnomalies` sweeps against.
 *   - `encounter_templates` — the reusable encounter table. `world_id`
 *     NULL is a GLOBAL template every world may roll; a non-NULL
 *     world_id scopes it. `assistant_driven` and `active` are TEXT
 *     enums, not 0/1 — see the note below.
 *   - `encounter_rolls` — append-only ledger of what actually fired.
 *     One row per roll. `cooldown_until` is the per-template cooldown
 *     cursor: a template whose newest roll has `cooldown_until > now`
 *     is ineligible.
 *
 * NO INTEGER BOOLEANS. `assistant_driven`/`active` would be
 * `.addColumn(..., "integer", ...)` with 0/1, which reads back as a
 * number and forces every caller into a truthiness coercion. Both are
 * TEXT with a CHECK constraint instead: `assistant_driven` is
 * automatic|assistant, `active` is enabled|disabled. The same applies
 * to `interaction_required` on an anomaly (optional|required).
 *
 * FK conventions follow 052/053: `worlds.id` cascades, text
 * timestamps default to `datetime('now')`.
 */
import { type Kysely, sql, } from "kysely";

/** Shared id primary key: 32 hex chars, generated by SQLite. */
const ID_DEFAULT = sql.raw("(lower(hex(randomblob(16))))",);

/** Shared creation timestamp. */
const NOW_DEFAULT = sql.raw("(datetime('now'))",);

export async function up(database: Kysely<unknown>,): Promise<void> {
  await database.schema
    .createTable("location_anomalies",)
    .addColumn("id", "text", (col,) => col.primaryKey().defaultTo(ID_DEFAULT,),)
    .addColumn("location_id", "text", (col,) => col.notNull().references("locations.id",).onDelete("cascade",),)
    .addColumn("world_id", "text", (col,) => col.notNull().references("worlds.id",).onDelete("cascade",),)
    .addColumn("name", "text", (col,) => col.notNull(),)
    /** positive | negative | neutral — the flavor axis the GM prompt reads. */
    .addColumn("type", "text", (col,) => col.notNull().defaultTo("neutral",),)
    /** `{"strength": 2, "luck": -1}` — additive stat deltas. */
    .addColumn("stat_modifiers", "text", (col,) => col.notNull().defaultTo("{}",),)
    .addColumn("damage_over_time", "real", (col,) => col.notNull().defaultTo(0,),)
    .addColumn("healing_over_time", "real", (col,) => col.notNull().defaultTo(0,),)
    .addColumn("experience_multiplier", "real", (col,) => col.notNull().defaultTo(1,),)
    .addColumn("loot_multiplier", "real", (col,) => col.notNull().defaultTo(1,),)
    /** JSON array of free-form effect ids the GM layer interprets. */
    .addColumn("special_effects", "text", (col,) => col.notNull().defaultTo("[]",),)
    /** Seconds the anomaly lives; -1 = permanent (leaves expires_at NULL). */
    .addColumn("duration_seconds", "integer", (col,) => col.notNull().defaultTo(-1,),)
    /** 0..1 chance a discovery roll succeeds for this anomaly. */
    .addColumn("discovery_chance", "real", (col,) => col.notNull().defaultTo(0,),)
    /** ISO instant the anomaly was first found; NULL while undiscovered. */
    .addColumn("discovered_at", "text",)
    .addColumn("interaction_required", "text", (col,) => col.notNull().defaultTo("optional",),)
    /** ISO instant the sweep deletes this row; NULL when permanent. */
    .addColumn("expires_at", "text",)
    .addColumn("created_at", "text", (col,) => col.notNull().defaultTo(NOW_DEFAULT,),)
    .addCheckConstraint(
      "ck_location_anomalies_type",
      sql.raw("type IN ('positive', 'negative', 'neutral')",),
    )
    .addCheckConstraint(
      "ck_location_anomalies_interaction",
      sql.raw("interaction_required IN ('optional', 'required')",),
    )
    .addCheckConstraint(
      "ck_location_anomalies_discovery_chance",
      sql.raw("discovery_chance >= 0 AND discovery_chance <= 1",),
    )
    .execute();

  await database.schema
    .createIndex("idx_location_anomalies_location",)
    .on("location_anomalies",)
    .columns(["location_id",],)
    .execute();

  await database.schema
    .createIndex("idx_location_anomalies_world",)
    .on("location_anomalies",)
    .columns(["world_id",],)
    .execute();

  // The sweep's only predicate: `expires_at <= now`. Partial so permanent
  // anomalies (expires_at NULL) never occupy an index entry.
  await database.schema
    .createIndex("idx_location_anomalies_expires",)
    .on("location_anomalies",)
    .column("expires_at",)
    .where(sql<boolean>`expires_at IS NOT NULL`,)
    .execute();

  await database.schema
    .createTable("encounter_templates",)
    .addColumn("id", "text", (col,) => col.primaryKey().defaultTo(ID_DEFAULT,),)
    /** NULL = global template available to every world. */
    .addColumn("world_id", "text", (col,) => col.references("worlds.id",).onDelete("cascade",),)
    .addColumn("name", "text", (col,) => col.notNull(),)
    .addColumn("type", "text", (col,) => col.notNull().defaultTo("event",),)
    .addColumn("trigger_type", "text", (col,) => col.notNull().defaultTo("random",),)
    /** 0..1 chance a candidate that passed eligibility fires. */
    .addColumn("trigger_chance", "real", (col,) => col.notNull().defaultTo(0,),)
    /** Seconds a fired template is excluded from further rolls. */
    .addColumn("cooldown_seconds", "integer", (col,) => col.notNull().defaultTo(0,),)
    /** 0..100 base difficulty; the roll jitters ±10 around it. */
    .addColumn("difficulty", "integer", (col,) => col.notNull().defaultTo(0,),)
    .addColumn("requirements", "text", (col,) => col.notNull().defaultTo("{}",),)
    .addColumn("rewards", "text", (col,) => col.notNull().defaultTo("{}",),)
    .addColumn("consequences", "text", (col,) => col.notNull().defaultTo("{}",),)
    /** Free-text LLM context describing how this encounter should read. */
    .addColumn("story_notes", "text",)
    .addColumn("assistant_driven", "text", (col,) => col.notNull().defaultTo("automatic",),)
    /** departure | journey | arrival; NULL = fires in any travel phase. */
    .addColumn("travel_phase", "text",)
    .addColumn("active", "text", (col,) => col.notNull().defaultTo("enabled",),)
    .addColumn("created_at", "text", (col,) => col.notNull().defaultTo(NOW_DEFAULT,),)
    .addCheckConstraint(
      "ck_encounter_templates_type",
      sql.raw("type IN ('combat', 'dialogue', 'event', 'puzzle', 'trade', 'quest')",),
    )
    .addCheckConstraint(
      "ck_encounter_templates_trigger_type",
      sql.raw(
        "trigger_type IN ('random', 'location_based', 'time_based', 'quest_based', 'story_based', 'travel_based')",
      ),
    )
    .addCheckConstraint(
      "ck_encounter_templates_assistant_driven",
      sql.raw("assistant_driven IN ('automatic', 'assistant')",),
    )
    .addCheckConstraint(
      "ck_encounter_templates_active",
      sql.raw("active IN ('enabled', 'disabled')",),
    )
    .addCheckConstraint(
      "ck_encounter_templates_travel_phase",
      sql.raw("travel_phase IS NULL OR travel_phase IN ('departure', 'journey', 'arrival')",),
    )
    .execute();

  // Every roll reads by (trigger_type, active) and filters world_id, so the
  // index leads on the selective columns.
  await database.schema
    .createIndex("idx_encounter_templates_trigger",)
    .on("encounter_templates",)
    .columns(["trigger_type", "active", "world_id",],)
    .execute();

  await database.schema
    .createTable("encounter_rolls",)
    .addColumn("id", "text", (col,) => col.primaryKey().defaultTo(ID_DEFAULT,),)
    .addColumn("world_id", "text", (col,) => col.notNull().references("worlds.id",).onDelete("cascade",),)
    .addColumn("location_id", "text", (col,) => col.references("locations.id",).onDelete("cascade",),)
    .addColumn(
      "template_id",
      "text",
      (col,) => col.notNull().references("encounter_templates.id",).onDelete("cascade",),
    )
    .addColumn("rolled_at", "text", (col,) => col.notNull().defaultTo(NOW_DEFAULT,),)
    .addColumn("difficulty_rolled", "integer", (col,) => col.notNull().defaultTo(0,),)
    .addColumn("outcome", "text", (col,) => col.notNull().defaultTo("{}",),)
    /** ISO instant the template becomes eligible again; NULL = no cooldown. */
    .addColumn("cooldown_until", "text",)
    .execute();

  // Cooldown probe: newest roll per template, compared against `now`.
  await database.schema
    .createIndex("idx_encounter_rolls_template",)
    .on("encounter_rolls",)
    .columns(["template_id", "rolled_at",],)
    .execute();

  await database.schema
    .createIndex("idx_encounter_rolls_world",)
    .on("encounter_rolls",)
    .columns(["world_id", "rolled_at",],)
    .execute();
}

