  await database.schema.dropTable("encounter_rolls",).execute();
  await database.schema.dropIndex("idx_encounter_templates_trigger",).execute();
  await database.schema.dropTable("encounter_templates",).execute();
  await database.schema.dropIndex("idx_location_anomalies_expires",).execute();
  await database.schema.dropIndex("idx_location_anomalies_world",).execute();
  await database.schema.dropIndex("idx_location_anomalies_location",).execute();
