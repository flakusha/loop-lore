/**
 * Ren'Py script generator — pure .rpy text builder over the normalized
 * export model. No DB, no filesystem, no network: deterministic output for
 * a given model, covered by bun:test.
 *
 * Each chat renders as one label: its played path (root-to-tip messages of
 * the active branch) inline, with a `menu:` block at each fork point
 * listing the sibling-branch stubs that share it. `characters.rpy` holds
 * one `define` per character; images are keyed so the route step can drop
 * avatar bytes at the matching path.
 */
import type { RenpyCharacter, RenpyExportChat, RenpyExportModel, } from "./types";

const MAX_SLUG = 40;

/**
 * Slugify a display name into a Ren'Py identifier: lowercase alnum +
 * underscore, capped at 40 chars, never empty.
 * @param name - display name to slugify
 * @returns a valid Ren'Py identifier fragment
 */
export function slugify(name: string,): string {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_",)
    .replace(/^_+|_+$/g, "",)
    .slice(0, MAX_SLUG,);
  return slug || "unnamed";
}

/**
 * Escape a string for a double-quoted Ren'Py string literal.
 * @param text - raw text
 * @returns text safe inside `"..."`
 */
export function escapeRenpy(text: string,): string {
  return text
    .replace(/\\/g, "\\\\",)
    .replace(/"/g, '\\"',)
    .replace(/\n/g, "\\n",);
}

/**
 * Unique slugs in order: first wins, later ones take `_2`, `_3`.
 * @param names - display names in first-seen order
 * @returns one unique slug per name
 */
export function uniqueSlugs(names: string[],): string[] {
  const seen = new Set<string>();
  return names.map((name,) => {
    const base = slugify(name,);
    let slug = base;
    let n = 2;
    while (seen.has(slug,)) {
      slug = `${base}_${n}`;
      n += 1;
    }
    seen.add(slug,);
    return slug;
  },);
}

/** One `define <slug> = Character("Display")` line per character. */
function charactersRpy(characters: RenpyCharacter[],): string {
  const lines = [
    "# Generated by loop-lore renpy-export — character definitions.",
    "",
  ];
  for (const c of characters) {
    const image = c.assetId ? `, image="images/${c.slug}.png"` : "";
    lines.push(`define ${c.slug} = Character("${escapeRenpy(c.displayName,)}"${image})`,);
  }
  lines.push("",);
  return lines.join("\n",);
}

function sayLine(speaker: string, text: string,): string {
  if (!speaker) { return `    "${escapeRenpy(text,)}"`; }
  return `    ${speaker} "${escapeRenpy(text,)}"`;
}

/**
 * Render one chat label: comment header, played-path say lines, one
 * indented `menu:` block at each fork point (sibling stubs jump out),
 * then the stub labels with TODO markers for the author.
 * @param chat - one exported chat
 * @returns script.rpy lines for this chat's label
 */
function chatLabel(chat: RenpyExportChat,): string[] {
  const lines = [`label ${chat.label}:`, `    # ${chat.name}`, "",];
  for (const m of chat.messages) {
    lines.push(sayLine(m.speaker, m.text,),);
  }
  for (const stub of chat.stubs) {
    lines.push("", "    menu:", `        "${escapeRenpy(stub.label,)}":`, `            jump ${stub.target}`,);
  }
  lines.push("", "    return", "",);
  for (const stub of chat.stubs) {
    lines.push(
      `label ${stub.target}:`,
      `    # TODO: author the "${stub.label}" branch in Ren'Py.`,
      '    "(Branch stub — finish in Ren\'Py.)"',
      "    return",
      ""
    );
  }
  return lines;
}

/**
 * Build the project text files from the normalized model.
 * @param model - gathered export model
 * @returns `game/script.rpy`, `game/characters.rpy`, `README.md` texts
 */
export function buildProjectFiles(model: RenpyExportModel,): Record<string, string> {
  const script: string[] = [
    "# Generated by loop-lore renpy-export.",
    "# Create a project in the Ren'Py Launcher, then drop game/ over it.",
    "",
  ];
  script.push("label start:", ...model.chats.flatMap((c,) => [`    call ${c.label}`,]), "    return", "",);
  for (const chat of model.chats) {
    script.push(...chatLabel(chat,),);
  }
  // Collapse 3+ blank runs (fork menus + stub sections stack them); pass
  // once over the joined lines so output never drifts between edits.
  const collapsed = script
    .join("\n",)
    .replace(/\n{3,}/g, "\n\n",);
  return {
    "game/script.rpy": collapsed,
    "game/characters.rpy": charactersRpy(model.characters,),
    "README.md": [
      "# Ren'Py export overlay",
      "",
      "1. Create a new project in the Ren'Py Launcher.",
      "2. Copy `game/` over the project's `game/` directory.",
      "3. Launch — `label start` lists each exported chat.",
      "",
    ].join("\n",),
  };
}
